function initialLocale() {
  const query = new URL(location.href).searchParams.get('lang');
  if (SUPPORTED.has(query)) return query;
  const stored = localStorage.getItem(STORAGE_KEY);
  if (SUPPORTED.has(stored)) return stored;
  return navigator.language.toLowerCase().startsWith('en') ? 'en' : 'ru';
}

let locale = initialLocale();

export function getLocale() {
  return locale;
}

export function t(key, values = {}) {
  const template = messages[locale][key] ?? messages.ru[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function modifierText(modifier) {
  if (!modifier) return { name: '', description: '' };
  const nameKey = `modifier.${modifier.id}.name`;
  const descriptionKey = `modifier.${modifier.id}.description`;
  const name = t(nameKey);
  const description = t(descriptionKey);
  return {
    name: name === nameKey ? (modifier.name || '') : name,
    description: description === descriptionKey ? (modifier.description || '') : description
  };
}

export function applyTranslations(root = document) {
  document.documentElement.lang = locale;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
  document.querySelector('meta[property="og:title"]')?.setAttribute('content', t('meta.title'));
  document.querySelector('meta[property="og:description"]')?.setAttribute('content', t('meta.description'));
  document.querySelector('meta[name="twitter:title"]')?.setAttribute('content', t('meta.title'));
  document.querySelector('meta[name="twitter:description"]')?.setAttribute('content', t('meta.description'));
  document.querySelector('meta[property="og:locale"]')?.setAttribute('content', locale === 'en' ? 'en_US' : 'ru_RU');
  const structuredData = document.querySelector('#structuredData');
  if (structuredData) {
    const schema = JSON.parse(structuredData.textContent);
    schema.inLanguage = locale;
    schema.description = t('meta.description');
    structuredData.textContent = JSON.stringify(schema);
  }
  root.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  for (const [attribute, dataset] of [['placeholder', 'i18nPlaceholder'], ['title', 'i18nTitle'], ['aria-label', 'i18nAriaLabel']]) {
    root.querySelectorAll(`[data-${dataset.replace(/[A-Z]/g, value => `-${value.toLowerCase()}`)}]`)
      .forEach(node => node.setAttribute(attribute, t(node.dataset[dataset])));
  }
  root.querySelectorAll('[data-locale]').forEach(button => {
    const active = button.dataset.locale === locale;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

export function setLocale(nextLocale) {
  if (!SUPPORTED.has(nextLocale) || nextLocale === locale) return;
  locale = nextLocale;
  localStorage.setItem(STORAGE_KEY, locale);
  const url = new URL(location.href);
  url.searchParams.set('lang', locale);
  history.replaceState(null, '', url);
  applyTranslations();
  window.dispatchEvent(new CustomEvent('dcb:localechange', { detail: { locale } }));
}

export function initI18n() {
  applyTranslations();
  document.querySelectorAll('[data-locale]').forEach(button => button.addEventListener('click', () => setLocale(button.dataset.locale)));
}
